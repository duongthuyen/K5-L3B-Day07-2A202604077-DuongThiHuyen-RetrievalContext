"""Step 3 — build chunks from text + tables + visual descriptions, embed, store in pgvector.

Chunk kinds (one shared index, kind kept as metadata):
- text   : paragraph-aware chunks of the page text layer (<= 1000 chars), id ADV:p0236:t00
- table  : PyMuPDF find_tables() markdown + caption found on the page, id ADV:p0236:tab0
- visual : one per non-decorative element from describe.py (chart/diagram/image/table),
           id ADV:p0236:v0, text = label + kind + title + details + summary
Every chunk keeps page (1-based PDF page), printed_page, chapter, section, label and the page render
path so the original region can be checked. Embedding: BAAI/bge-small-en-v1.5 (384-d, same as Day 6).
Run: python -m advanced.index
"""
from __future__ import annotations

import json
import re
import time

import psycopg

from .common import DATA, DATABASE_URL, TABLE

MAX_CHARS = 1000


def _text_chunks(p: dict) -> list[dict]:
    paras = [b.strip() for b in p["text"].split("\n\n") if b.strip()]
    chunks, cur = [], ""
    for para in paras:
        if cur and len(cur) + len(para) + 1 > MAX_CHARS:
            chunks.append(cur); cur = ""
        while len(para) > MAX_CHARS:  # very long paragraph: split at sentence boundary
            cut = para.rfind(". ", 0, MAX_CHARS)
            cut = cut + 1 if cut > 200 else MAX_CHARS
            chunks.append(para[:cut].strip()); para = para[cut:].strip()
        cur = f"{cur}\n{para}".strip()
    if cur:
        chunks.append(cur)
    return chunks


def _nearest_caption(p: dict, bbox, kind: str):
    caps = [c for c in p["captions"] if c["kind"] == kind]
    if not caps:
        return None
    return min(caps, key=lambda c: abs(c["bbox"][1] - bbox[3]) if bbox else 0)


def build_chunks() -> list[dict]:
    pages = [json.loads(l) for l in open(DATA / "pages.jsonl", encoding="utf-8")]
    chunks = []
    for p in pages:
        base = {"page": p["page"], "printed_page": p["printed_page"], "chapter": p["chapter"],
                "section": p["section"], "render": p["render"]}
        for i, t in enumerate(_text_chunks(p)):
            chunks.append({**base, "id": f"ADV:p{p['page']:04d}:t{i:02d}", "kind": "text", "label": None, "text": t})
        for i, tb in enumerate(t for t in p["tables"] if "markdown" in t):
            cap = _nearest_caption(p, tb["bbox"], "table")
            label = cap["label"] if cap else None
            head = f"{label}: {cap['caption']}\n" if cap else ""
            chunks.append({**base, "id": f"ADV:p{p['page']:04d}:tab{i}", "kind": "table", "label": label,
                           "bbox": tb["bbox"], "text": head + tb["markdown"][:4000]})
        vf = DATA / "visual" / f"p{p['page']:03d}.json"
        if vf.exists():
            v = json.loads(vf.read_text(encoding="utf-8"))
            els = [x if isinstance(x, dict) else {"kind": "image", "label": None, "details": str(x)} for x in v["elements"]]
            for i, e in enumerate(x for x in els if x.get("kind") != "decorative"):
                details = e.get("details")
                if not isinstance(details, str):
                    details = json.dumps(details, ensure_ascii=False)
                text = (f"{e.get('label') or 'Unlabeled'} ({e.get('kind')}) — {e.get('title') or ''}\n"
                        f"{details}\nSummary: {e.get('summary') or ''}\n[visual description generated by {v['model']}]")
                chunks.append({**base, "id": f"ADV:p{p['page']:04d}:v{i}", "kind": "visual",
                               "visual_kind": e.get("kind"), "label": e.get("label"), "text": text[:5000]})
    return chunks


def store(chunks: list[dict]) -> dict:
    from sentence_transformers import SentenceTransformer
    model = SentenceTransformer("BAAI/bge-small-en-v1.5", device="cpu")
    t0 = time.perf_counter()
    vecs = model.encode([c["text"] for c in chunks], batch_size=32, normalize_embeddings=True, show_progress_bar=False)
    embed_s = time.perf_counter() - t0
    with psycopg.connect(DATABASE_URL) as conn:
        conn.execute("CREATE EXTENSION IF NOT EXISTS vector")
        conn.execute(f"DROP TABLE IF EXISTS {TABLE}")
        conn.execute(f"""CREATE TABLE {TABLE} (id TEXT PRIMARY KEY, page INT NOT NULL, printed_page INT,
                         kind TEXT NOT NULL, label TEXT, chapter TEXT, section TEXT, content TEXT NOT NULL,
                         metadata JSONB NOT NULL, embedding vector(384) NOT NULL)""")
        with conn.cursor() as cur:
            for c, v in zip(chunks, vecs):
                meta = {k: c.get(k) for k in ("render", "bbox", "visual_kind")}
                cur.execute(f"INSERT INTO {TABLE} VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s::vector)",
                            (c["id"], c["page"], c["printed_page"], c["kind"], c["label"], c["chapter"], c["section"],
                             c["text"], json.dumps(meta), "[" + ",".join(f"{x:.7f}" for x in v) + "]"))
    return {"chunks": len(chunks), "by_kind": {k: sum(c["kind"] == k for c in chunks) for k in ("text", "table", "visual")},
            "pages": len({c["page"] for c in chunks}), "embed_seconds": round(embed_s, 1),
            "embedding_model": "BAAI/bge-small-en-v1.5", "dim": 384, "store": f"pgvector table {TABLE}"}


def main() -> None:
    chunks = build_chunks()
    (DATA / "chunks.json").write_text(json.dumps(chunks, ensure_ascii=False, indent=0), encoding="utf-8")
    rep = store(chunks)
    (DATA / "index_report.json").write_text(json.dumps(rep, indent=2), encoding="utf-8")
    print(rep)


if __name__ == "__main__":
    main()
